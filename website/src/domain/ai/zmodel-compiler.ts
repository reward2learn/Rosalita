/**
 * ZenStack .zmodel Compiler
 *
 * Takes an AI-generated SchemaGenerationResult and compiles it
 * into a valid ZenStack schema.zmodel file.
 *
 * The generated .zmodel includes:
 *   - datasource + generator blocks
 *   - AuthTier enum
 *   - All models with proper field types, decorators, and @@map
 */

import type { SchemaGenerationResult, GeneratedField } from './schema-generation-schema';

// ── Field type mapping ──────────────────────────────────

function mapFieldType(field: GeneratedField): string {
  switch (field.type) {
    case 'string':   return 'String';
    case 'text':     return 'String @db.Text';
    case 'integer':  return 'Int';
    case 'decimal':  return 'Decimal @db.Decimal(14, 2)';
    case 'boolean':  return 'Boolean';
    case 'datetime': return 'DateTime';
    case 'date':     return 'DateTime @db.Date';
    case 'time':     return 'DateTime @db.Time';
    case 'enum':     return 'String';
    case 'json':     return 'Json';
    case 'relation': return 'String';
    default:         return 'String';
  }
}

// ── Field decorator mapping ─────────────────────────────

function mapFieldDecorators(field: GeneratedField): string {
  const parts: string[] = [];

  if (field.unique) parts.push('@unique');
  if (field.default !== undefined) {
    if (typeof field.default === 'string') {
      parts.push(`@default("${field.default}")`);
    } else if (typeof field.default === 'boolean') {
      parts.push(`@default(${field.default})`);
    } else if (typeof field.default === 'number') {
      parts.push(`@default(${field.default})`);
    } else if (Array.isArray(field.default)) {
      parts.push(`@default([])`);
    } else {
      parts.push(`@default("{}")`);
    }
  }

  return parts.length > 0 ? ' ' + parts.join(' ') : '';
}

// ── Field comment (schema.org mapping) ──────────────────

function mapFieldComment(field: GeneratedField): string | null {
  if (!field.schemaOrgProperty) return null;
  return `  /// schema.org:${field.schemaOrgProperty}`;
}

// ── Model compilation ───────────────────────────────────

function compileModel(model: SchemaGenerationResult['models'][0]): string {
  const fieldsStr = model.fields.map(f => {
    const typeStr = mapFieldType(f);
    const optional = f.required ? '' : '?';
    const decorators = mapFieldDecorators(f);
    const comment = mapFieldComment(f);
    const fieldLine = `  ${f.name} ${typeStr}${optional}${decorators}`;

    return comment ? `${comment}\n${fieldLine}` : fieldLine;
  }).join('\n');

  return `
model ${model.name} {
  id         String   @id @default(cuid())
  tenantSlug String?  @map("tenant_slug")
${fieldsStr}
  createdAt  DateTime @default(now()) @map("created_at")
  updatedAt  DateTime @updatedAt @map("updated_at")

  @@index([tenantSlug])
  @@map("${model.tableName}")
}`;
}

// ── Full .zmodel compilation ────────────────────────────

export function compileToZModel(schema: SchemaGenerationResult): string {
  const header = `// Auto-generated ZenStack schema for ${schema.templateId}
// Generated by TOKENIZMYAPP AI Schema Generator
// schema.org type: ${schema.schemaOrgType}
// W3C standard alignment applied to field types

datasource db {
  provider = "postgresql"
  url      = env("POSTGRES_URL")
}

generator client {
  provider = "prisma-client-js"
  output   = "../../src/generated/prisma"
  binaryTargets = ["native", "linux-arm64-openssl-3.0.x"]
}

enum AuthTier {
  public
  pin
  google
}
`;

  const models = schema.models.map(compileModel).join('\n');

  return `${header}\n${models}\n`;
}

// ── Page catalog compilation ────────────────────────────

export function compileToPageCatalog(schema: SchemaGenerationResult): string {
  const pages = schema.pages.map(p => `  {
    slug: '${p.slug}',
    title: '${p.title}',
    authTier: '${p.authTier}',
    navLabel: '${p.navLabel ?? p.title}',
    sections: [
      ${p.blockTypes.map((bt, i) => `{ blockType: '${bt}' as BlockType, config: {} }`).join(',\n      ')}
    ],
  }`).join(',\n');

  return `/**
 * Auto-generated page catalog for ${schema.templateId}
 * Generated by TOKENIZMYAPP AI Schema Generator
 */
import type { PageDefinition } from '@/lib/page-catalog';

export const GENERATED_PAGES: PageDefinition[] = [
${pages}
];
`;
}
